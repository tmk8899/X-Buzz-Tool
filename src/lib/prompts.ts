const PATTERN_POOL = [
  "共感型",
  "逆張り型",
  "アルゴリズム型",
  "データ型",
  "失敗談型",
  "比較型",
  "暴露型",
  "ストーリー型",
  "チェックリスト型",
  "結論先出し型",
  "問いかけ型",
  "体験告白型",
  "数字インパクト型",
  "常識破壊型",
];

function pickRandomItems<T>(arr: T[], count: number): T[] {
  const copy = [...arr];
  const result: T[] = [];
  while (copy.length && result.length < count) {
    const index = Math.floor(Math.random() * copy.length);
    result.push(copy.splice(index, 1)[0]);
  }
  return result;
}

/**
 * generate-post API 用のプロンプト。
 * バズ投稿の「型」を実際の構造指示に展開し、Xの最新アルゴリズムのシグナルを踏まえた
 * 3案を生成させる。
 */
export function buildGeneratePostPrompt(input: GeneratePostInput): string {
  const toneInstruction = TONE_INSTRUCTIONS[input.tone] ?? input.tone;
  const selectedPatterns = pickRandomItems(PATTERN_POOL, 3);
  const randomSeed = Math.random().toString(36).slice(2, 8);
  const timeStamp = new Date().toLocaleString("ja-JP");

  return `
あなたはX投稿専用のSNSコピーライターです。Xの最新レコメンドアルゴリズムを熟知しており、
リプライ・滞在時間・初速エンゲージメントを稼ぎやすい、完全オリジナルの日本語投稿を3案生成してください。

${ALGORITHM_GUIDELINES}

【生成ID: ${randomSeed} / ${timeStamp}】
※ 毎回必ず異なる切り口・表現・構成にすること。過去の出力と被らないようにすること。

【テーマ】
${input.topic}

【ターゲット】
${input.target}

【目的】
${input.purpose}

【バズ投稿の型・構造指示】
${toneInstruction}

【文字数目安】
${input.maxChars}文字前後（テーマに厚みがあれば目安を超えて読み応えを優先してよい）

【投稿パターン（3案それぞれ異なる型を使うこと）】
${selectedPatterns.join(" / ")}

【ペルソナ（最重要・必ずこの人物として書くこと）】
${input.persona
  ? `名前: ${input.persona.name}\nトーン・スタイル: ${input.persona.tone || "指定なし"}\n→ 上記のトーン・スタイルを最優先で文体・口調に反映させること`
  : "指定なし"}

【追加指示】
${input.customInstruction || "なし"}

【絶対ルール】
- 3案は必ず互いに全く異なる内容・切り口・文体にすること
- 同じ出だし・同じ展開は禁止
- テンプレート的な表現は使わない
- ハッシュタグ禁止
- 外部リンクを本文に含めない
- AIっぽい説明口調を避ける
- 「いいね・RT・フォローして」のような直接的なエンゲージメント誘導は禁止。自然に返信・共感したくなる余白を作る
- 1文目で強く引きつける（冒頭100〜140文字＝フィードのプレビューで完結する内容にする）
- 常識を少し壊すか、不安・違和感・意外性を入れる（誤解を招く言い切りは避ける）
- 人間が実際にXへ投稿する文体にする
- 説明しすぎず余白を残しつつ、最後まで読ませる厚みを持たせる
- 短文中心で改行を自然に入れる
- ペルソナのトーンが絵文字使用を示している場合のみ絵文字を使ってよい

【出力形式】
以下のJSON配列のみを出力すること。コードブロックや説明文は不要。

[
  {
    "title": "投稿タイトル（内部管理用）",
    "hook": "フック文（冒頭1〜2文）",
    "body": "本文",
    "cta": "CTA文（不要なら空文字）",
    "hashtags": [],
    "full_post": "hook + body + ctaを自然につなげた完成形の投稿文"
  },
  { ... },
  { ... }
]
`.trim();
}

const REWRITE_GOAL_LABELS: Record<string, string> = {
  viral: "バズらせる（フック強化・拡散されやすい表現に）",
  concise: "簡潔にする（不要な言葉を削り、テンポよく）",
  engaging: "エンゲージメント強化（共感・返信したくなる問いかけを促す。直接的な「いいね/RTして」は使わない）",
  formal: "フォーマルに（丁寧で信頼感のある文体に）",
  casual: "カジュアルに（親しみやすい口語体に）",
  hook: "書き出し強化（冒頭100〜140文字＝フィードのプレビューで完結する強いフックにする）",
};

/**
 * rewrite API 用のプロンプト。
 */
export function buildRewritePrompt(original: string, goal: string): string {
  const goalLabel = REWRITE_GOAL_LABELS[goal] ?? REWRITE_GOAL_LABELS.viral;
  const seed = Math.random().toString(36).slice(2, 8);

  return `
あなたはX投稿専門のリライターです。Xの最新レコメンドアルゴリズムを踏まえて、
以下の投稿を「${goalLabel}」という目的でリライトしてください。

${ALGORITHM_GUIDELINES}

【元の投稿】
${original}

【リライト方針】
- 元の内容・意図は保ちつつ、表現を大きく改善する
- 目的（${goalLabel}）を最優先で反映する
- ハッシュタグ禁止
- 外部リンクを本文に含めない
- 「いいね・RT・フォローして」のような直接的なエンゲージメント誘導は禁止
- AIっぽい説明口調を避ける
- 人間が自然にXに投稿する文体にする
- 冒頭100〜140文字（フィードのプレビュー範囲）だけで意味が完結するようにする
- 改行・テンポを意識する
- シード: ${seed}

【出力】
リライト後の投稿文のみを出力してください。説明や前置きは不要です。
`.trim();
}
